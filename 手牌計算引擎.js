function 驗證輸入(和牌條件) {
  const 手牌張數 = 和牌條件.手牌.length;
  const 應有手牌張數 = 14 - 和牌條件.副露清單.length * 3;
  if (手牌張數 !== 應有手牌張數) {
    return { 通過: false, 錯誤訊息: `手牌張數不對：目前 ${手牌張數} 張，有 ${和牌條件.副露清單.length} 組副露時應為 ${應有手牌張數} 張` };
  }
  if (!和牌條件.手牌.includes(和牌條件.和牌張)) {
    return { 通過: false, 錯誤訊息: '尚未指定和牌張，或和牌張不在手牌中' };
  }
  const 全部牌張統計 = 統計全部牌張(和牌條件);
  for (let 牌 = 0; 牌 < 牌總數; 牌++) {
    if (全部牌張統計[牌] > 4) {
      return { 通過: false, 錯誤訊息: `${牌名稱表[牌]} 超過四張` };
    }
  }
  if (和牌條件.是自摸 && 和牌條件.是搶槓) {
    return { 通過: false, 錯誤訊息: '搶槓只會發生在榮和，不能同時選自摸' };
  }
  if (!和牌條件.是自摸 && 和牌條件.是嶺上開花) {
    return { 通過: false, 錯誤訊息: '嶺上開花只會發生在自摸，不能同時選榮和' };
  }
  if (和牌條件.是自摸 && 和牌條件.是河底撈魚) {
    return { 通過: false, 錯誤訊息: '河底撈魚是榮和限定，自摸請選海底摸月' };
  }
  if (!和牌條件.是自摸 && 和牌條件.是海底摸月) {
    return { 通過: false, 錯誤訊息: '海底摸月是自摸限定，榮和請選河底撈魚' };
  }
  return { 通過: true };
}

/**
 * 計算和牌的番數、符數與點數。
 * 同一副手牌常有多種拆解方式，逐一計算後取點數最高者，這是日本麻將的通則。
 */
function 計算和牌結果(和牌條件) {
  const 驗證結果 = 驗證輸入(和牌條件);
  if (!驗證結果.通過) return { 成功: false, 錯誤訊息: 驗證結果.錯誤訊息 };

  const 是莊家 = 和牌條件.自風牌 === 東風編號;
  const 和牌形清單 = 產生所有和牌形(和牌條件);
  if (和牌形清單.length === 0) {
    return {
      成功: false,
      錯誤訊息: '這副手牌不成和牌型（四面子一雀頭、七對子、國士無雙都不成立）',
      是詐和: true,
      詐和罰符: 計算詐和罰符(是莊家)
    };
  }

  const 全部牌張統計 = 統計全部牌張(和牌條件);
  const 寶牌結果 = 計算寶牌番數(和牌條件, 全部牌張統計);
  const 寶牌總番數 = 寶牌結果.寶牌數 + 寶牌結果.赤寶牌數;

  let 最佳結果 = null;
  let 曾成和牌型但無役 = false;

  for (const 和牌形 of 和牌形清單) {
    const 役判定 = 判定所有役(和牌形, 和牌條件);
    if (役判定.役滿清單.length === 0 && 役判定.普通役清單.length === 0) {
      曾成和牌型但無役 = true;
      continue;
    }
    const 符計算 = 計算符數(和牌形, 和牌條件, 役判定.普通役清單);
    const 役番數合計 = 役判定.普通役清單.reduce((累計, 役) => 累計 + 役.番數, 0);
    const 總番數 = 役判定.役滿總倍數 > 0 ? 役番數合計 : 役番數合計 + 寶牌總番數;
    const 點數結果 = 計算點數(總番數, 符計算.符數, 役判定.役滿總倍數, 是莊家, 和牌條件.是自摸, 和牌條件.連莊數);

    const 本次結果 = {
      成功: true,
      和牌形狀: 和牌形.形狀,
      待牌形: 和牌形.待牌形,
      面子描述清單: 建立面子描述清單(和牌形),
      役滿清單: 役判定.役滿清單,
      普通役清單: 役判定.普通役清單,
      役番數合計,
      寶牌結果,
      寶牌總番數: 役判定.役滿總倍數 > 0 ? 0 : 寶牌總番數,
      總番數,
      符數: 符計算.符數,
      符數明細: 符計算.符數明細,
      是莊家,
      是自摸: 和牌條件.是自摸,
      點數結果
    };

    if (最佳結果 === null || 比較何者較優(本次結果, 最佳結果) > 0) {
      最佳結果 = 本次結果;
    }
  }

  if (最佳結果 === null) {
    const 補充 = 曾成和牌型但無役 ? '牌型雖然湊齊，但沒有任何役。寶牌本身不算役，不能和牌。' : '';
    return {
      成功: false,
      錯誤訊息: '無役，不能和牌。' + 補充,
      是詐和: true,
      詐和罰符: 計算詐和罰符(是莊家)
    };
  }
  return 最佳結果;
}

/** 點數高者優先；點數相同時取番數高者，再取符數高者 */
function 比較何者較優(結果甲, 結果乙) {
  if (結果甲.點數結果.總點數 !== 結果乙.點數結果.總點數) {
    return 結果甲.點數結果.總點數 - 結果乙.點數結果.總點數;
  }
  if (結果甲.總番數 !== 結果乙.總番數) return 結果甲.總番數 - 結果乙.總番數;
  return 結果甲.符數 - 結果乙.符數;
}

function 建立面子描述清單(和牌形) {
  if (和牌形.形狀 === '國士無雙') {
    return [`國士無雙型，${牌名稱表[和牌形.雀頭牌]} 成對`];
  }
  if (和牌形.形狀 === '七對子') {
    return ['七對子型'];
  }
  const 描述清單 = [`雀頭 ${牌名稱表[和牌形.雀頭牌]}`];
  for (const 面子 of 和牌形.面子清單) {
    描述清單.push(描述面子(面子) + (面子.來自副露 ? '（副露）' : ''));
  }
  return 描述清單;
}

