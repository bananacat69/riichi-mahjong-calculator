/** 取得一組刻子或槓子的符數 */
function 取得刻子槓子符數(面子) {
  const 是么九 = 是么九或字牌(面子.起始牌);
  if (面子.種類 === '刻子') {
    if (面子.是暗的) return 是么九 ? 8 : 4;
    return 是么九 ? 4 : 2;
  }
  if (面子.是暗的) return 是么九 ? 32 : 16;
  return 是么九 ? 16 : 8;
}

function 描述面子(面子) {
  const 牌名 = 牌名稱表[面子.起始牌];
  if (面子.種類 === '順子') {
    return `順子 ${牌名}${牌名稱表[面子.起始牌 + 1]}${牌名稱表[面子.起始牌 + 2]}`;
  }
  const 明暗 = 面子.是暗的 ? '暗' : '明';
  return `${明暗}${面子.種類 === '槓子' ? '槓' : '刻'} ${牌名}`;
}

/**
 * 計算符數，同時產出可顯示的明細。
 */
function 計算符數(和牌形, 和牌條件, 普通役清單) {
  if (和牌形.形狀 === '七對子') {
    return { 符數: 25, 符數明細: [{ 項目: '七對子固定符', 符: 25 }] };
  }

  const 符數明細 = [{ 項目: '副底', 符: 20 }];
  let 符數合計 = 20;

  if (和牌形.是門前 && !和牌條件.是自摸) {
    符數明細.push({ 項目: '門前榮和', 符: 10 });
    符數合計 += 10;
  }
  if (和牌條件.是自摸) {
    符數明細.push({ 項目: '自摸', 符: 2 });
    符數合計 += 2;
  }

  for (const 面子 of 和牌形.面子清單) {
    if (面子.種類 === '順子') continue;
    const 面子符數 = 取得刻子槓子符數(面子);
    if (面子符數 > 0) {
      符數明細.push({ 項目: 描述面子(面子), 符: 面子符數 });
      符數合計 += 面子符數;
    }
  }

  // 雀頭：三元牌、場風、自風各兩符；場風與自風相同（連風牌）時合計四符
  let 雀頭符數 = 0;
  if (三元牌清單.includes(和牌形.雀頭牌)) 雀頭符數 += 2;
  if (和牌形.雀頭牌 === 和牌條件.場風牌) 雀頭符數 += 2;
  if (和牌形.雀頭牌 === 和牌條件.自風牌) 雀頭符數 += 2;
  if (雀頭符數 > 0) {
    符數明細.push({ 項目: `雀頭 ${牌名稱表[和牌形.雀頭牌]}`, 符: 雀頭符數 });
    符數合計 += 雀頭符數;
  }

  if (和牌形.待牌形 === '單騎' || 和牌形.待牌形 === '嵌張' || 和牌形.待牌形 === '邊張') {
    符數明細.push({ 項目: `${和牌形.待牌形}聽`, 符: 2 });
    符數合計 += 2;
  }

  const 成立平和 = 普通役清單.some((役) => 役.名稱 === '平和');
  if (成立平和 && 和牌條件.是自摸) {
    return { 符數: 20, 符數明細: [{ 項目: '平和自摸固定符', 符: 20 }] };
  }
  if (!和牌形.是門前 && !和牌條件.是自摸 && 符數合計 === 20) {
    return { 符數: 30, 符數明細: [{ 項目: '副露平和型榮和固定符', 符: 30 }] };
  }

  const 切上後符數 = Math.ceil(符數合計 / 10) * 10;
  if (切上後符數 !== 符數合計) {
    符數明細.push({ 項目: `合計 ${符數合計} 符進位`, 符: 切上後符數 - 符數合計 });
  }
  return { 符數: 切上後符數, 符數明細 };
}

