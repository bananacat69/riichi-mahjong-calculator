/**
 * 把副露資料轉成統一的面子物件。
 * 副露種類：吃、碰、明槓、暗槓
 */
function 轉換副露為面子(副露) {
  if (副露.種類 === '吃') {
    return { 種類: '順子', 起始牌: 副露.起始牌, 是暗的: false, 來自副露: true, 含和牌張: false };
  }
  if (副露.種類 === '碰') {
    return { 種類: '刻子', 起始牌: 副露.起始牌, 是暗的: false, 來自副露: true, 含和牌張: false };
  }
  if (副露.種類 === '明槓') {
    return { 種類: '槓子', 起始牌: 副露.起始牌, 是暗的: false, 來自副露: true, 含和牌張: false };
  }
  return { 種類: '槓子', 起始牌: 副露.起始牌, 是暗的: true, 來自副露: true, 含和牌張: false };
}

/** 門前的定義：沒有吃、碰、明槓（暗槓不破壞門前） */
function 判斷是否門前(副露清單) {
  return 副露清單.every((副露) => 副露.種類 === '暗槓');
}

/**
 * 產生所有可能的和牌形。每一種「拆解方式 × 和牌張歸屬」都是一個獨立候選，
 * 因為兩者都會改變符數與役種，必須逐一計算後取最高點數。
 */
function 產生所有和牌形(和牌條件) {
  const 和牌形清單 = [];
  const 牌張數統計 = 統計手牌張數(和牌條件.手牌);
  const 副露面子清單 = 和牌條件.副露清單.map(轉換副露為面子);
  const 是門前 = 判斷是否門前(和牌條件.副露清單);

  // 國士無雙（僅限門前且完全無副露）
  if (和牌條件.副露清單.length === 0) {
    const 國士檢查 = 檢查國士無雙型(牌張數統計);
    if (國士檢查.成立) {
      和牌形清單.push({
        形狀: '國士無雙',
        是門前,
        雀頭牌: 國士檢查.對子牌,
        面子清單: [],
        待牌形: 國士檢查.對子牌 === 和牌條件.和牌張 ? '十三面' : '單騎',
        是十三面: 國士檢查.對子牌 === 和牌條件.和牌張
      });
    }
    // 七對子
    if (是七對子型(牌張數統計)) {
      和牌形清單.push({
        形狀: '七對子',
        是門前,
        雀頭牌: 和牌條件.和牌張,
        面子清單: [],
        待牌形: '單騎'
      });
    }
  }

  // 標準型：四面子一雀頭
  const 需要面子數 = 4 - 副露面子清單.length;
  for (const 拆解 of 列舉標準型拆解(牌張數統計)) {
    if (拆解.面子清單.length !== 需要面子數) continue;
    const 手牌面子清單 = 拆解.面子清單.map((面子) => ({
      種類: 面子.種類,
      起始牌: 面子.起始牌,
      是暗的: true,
      來自副露: false,
      含和牌張: false
    }));

    // 和牌張可能落在雀頭或任一手牌面子，逐一列舉
    const 和牌張歸屬候選 = [];
    if (拆解.雀頭牌 === 和牌條件.和牌張) {
      和牌張歸屬候選.push({ 位置: '雀頭', 面子索引: -1 });
    }
    手牌面子清單.forEach((面子, 索引) => {
      if (面子包含此牌(面子, 和牌條件.和牌張)) {
        和牌張歸屬候選.push({ 位置: '面子', 面子索引: 索引 });
      }
    });
    if (和牌張歸屬候選.length === 0) continue;

    for (const 歸屬 of 和牌張歸屬候選) {
      const 本候選面子清單 = 手牌面子清單.map((面子) => ({ ...面子 }));
      let 待牌形;
      if (歸屬.位置 === '雀頭') {
        待牌形 = '單騎';
      } else {
        const 和牌面子 = 本候選面子清單[歸屬.面子索引];
        和牌面子.含和牌張 = true;
        // 榮和時，被人打出的那張所完成的面子視為明的
        if (!和牌條件.是自摸) 和牌面子.是暗的 = false;
        待牌形 = 判斷待牌形(和牌面子, 和牌條件.和牌張);
      }
      和牌形清單.push({
        形狀: '標準',
        是門前,
        雀頭牌: 拆解.雀頭牌,
        面子清單: 本候選面子清單.concat(副露面子清單.map((面子) => ({ ...面子 }))),
        待牌形
      });
    }
  }

  return 和牌形清單;
}

function 面子包含此牌(面子, 牌編號) {
  if (面子.種類 === '順子') {
    return 牌編號 >= 面子.起始牌 && 牌編號 <= 面子.起始牌 + 2;
  }
  return 面子.起始牌 === 牌編號;
}

function 判斷待牌形(和牌面子, 和牌張) {
  if (和牌面子.種類 === '刻子' || 和牌面子.種類 === '槓子') return '雙碰';
  const 在順子中的位置 = 和牌張 - 和牌面子.起始牌; // 0 頭、1 中、2 尾
  if (在順子中的位置 === 1) return '嵌張';
  const 順子起始數字 = 取得牌面數字(和牌面子.起始牌);
  if (在順子中的位置 === 2 && 順子起始數字 === 1) return '邊張';
  if (在順子中的位置 === 0 && 順子起始數字 === 7) return '邊張';
  return '兩面';
}

function 統計手牌張數(手牌清單) {
  const 牌張數統計 = new Array(牌總數).fill(0);
  for (const 牌 of 手牌清單) 牌張數統計[牌]++;
  return 牌張數統計;
}

/** 把和牌形還原成完整的 34 種牌張數統計（含副露） */
function 統計和牌形全部牌張(和牌形) {
  const 牌張數統計 = new Array(牌總數).fill(0);
  if (和牌形.形狀 === '國士無雙') {
    for (const 牌 of 么九與字牌清單) 牌張數統計[牌] += 1;
    牌張數統計[和牌形.雀頭牌] += 1;
    return 牌張數統計;
  }
  if (和牌形.形狀 === '七對子') return null; // 七對子另行處理
  牌張數統計[和牌形.雀頭牌] += 2;
  for (const 面子 of 和牌形.面子清單) {
    if (面子.種類 === '順子') {
      牌張數統計[面子.起始牌]++;
      牌張數統計[面子.起始牌 + 1]++;
      牌張數統計[面子.起始牌 + 2]++;
    } else if (面子.種類 === '刻子') {
      牌張數統計[面子.起始牌] += 3;
    } else {
      牌張數統計[面子.起始牌] += 4;
    }
  }
  return 牌張數統計;
}

