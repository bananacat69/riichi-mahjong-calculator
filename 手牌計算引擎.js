/**
 * 由番數與符數算出實際收支。
 * 規則：無切上滿貫；十三番以上為累計役滿。
 * 連莊累積的本場，每一本場額外三百點：榮和由放銃者一人付，自摸由三家各付一百點。
 */
function 計算點數(總番數, 符數, 役滿總倍數, 是莊家, 是自摸, 連莊數) {
  const 本場數 = 連莊數 || 0;
  const 本場加成 = 本場數 * 300;
  const 每家本場加成 = 本場數 * 100;
  let 基本點;
  let 級別名稱 = '';

  if (役滿總倍數 > 0) {
    基本點 = 8000 * 役滿總倍數;
    級別名稱 = 役滿總倍數 === 1 ? '役滿' : `${役滿總倍數} 倍役滿`;
  } else if (總番數 >= 13) {
    基本點 = 8000; 級別名稱 = '累計役滿';
  } else if (總番數 >= 11) {
    基本點 = 6000; 級別名稱 = '三倍滿';
  } else if (總番數 >= 8) {
    基本點 = 4000; 級別名稱 = '倍滿';
  } else if (總番數 >= 6) {
    基本點 = 3000; 級別名稱 = '跳滿';
  } else if (總番數 === 5) {
    基本點 = 2000; 級別名稱 = '滿貫';
  } else {
    基本點 = 符數 * Math.pow(2, 2 + 總番數);
    if (基本點 >= 2000) {
      基本點 = 2000; 級別名稱 = '滿貫';
    }
  }

  if (!是自摸) {
    const 和牌點數 = 進位到百點(基本點 * (是莊家 ? 6 : 4));
    const 總點數 = 和牌點數 + 本場加成;
    return {
      級別名稱,
      和牌點數,
      本場數,
      本場加成,
      總點數,
      收支說明: `放銃者支付 ${格式化點數(總點數)} 點`,
      明細: { 放銃者支付: 總點數 }
    };
  }

  if (是莊家) {
    const 每家支付 = 進位到百點(基本點 * 2) + 每家本場加成;
    const 和牌點數 = 進位到百點(基本點 * 2) * 3;
    return {
      級別名稱,
      和牌點數,
      本場數,
      本場加成,
      總點數: 每家支付 * 3,
      收支說明: `子家各付 ${格式化點數(每家支付)} 點，合計 ${格式化點數(每家支付 * 3)} 點`,
      明細: { 子家支付: 每家支付, 合計: 每家支付 * 3 }
    };
  }

  const 莊家支付 = 進位到百點(基本點 * 2) + 每家本場加成;
  const 子家支付 = 進位到百點(基本點) + 每家本場加成;
  const 和牌點數 = 進位到百點(基本點 * 2) + 進位到百點(基本點) * 2;
  return {
    級別名稱,
    和牌點數,
    本場數,
    本場加成,
    總點數: 莊家支付 + 子家支付 * 2,
    收支說明: `莊家付 ${格式化點數(莊家支付)} 點，另外兩家各付 ${格式化點數(子家支付)} 點，合計 ${格式化點數(莊家支付 + 子家支付 * 2)} 點`,
    明細: { 莊家支付, 子家支付, 合計: 莊家支付 + 子家支付 * 2 }
  };
}

/**
 * 倒牌之後才發現不能和，就是詐和，要付滿貫罰符。
 * 莊家賠三家各四千，子家賠莊家四千、另外兩家各兩千。
 * 只喊了聲、手牌還沒倒的話，一般只判和牌放棄，不走這個罰則。
 */
function 計算詐和罰符(是莊家) {
  if (是莊家) {
    return {
      總點數: 12000,
      收支說明: '三家各收 4,000 點，合計賠出 12,000 點',
      明細: { 每家收取: 4000 }
    };
  }
  return {
    總點數: 8000,
    收支說明: '莊家收 4,000 點，另外兩家各收 2,000 點，合計賠出 8,000 點',
    明細: { 莊家收取: 4000, 子家收取: 2000 }
  };
}

