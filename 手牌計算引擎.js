/*
 * 日本麻將（立直麻將）番數與點數計算引擎
 * 規則基準：雀魂／天鳳標準（見「規則說明」區塊）
 *
 * 牌的內部編號（0 到 33）：
 *   0  到 8   萬子 一萬 到 九萬
 *   9  到 17  筒子 一筒 到 九筒
 *   18 到 26  索子 一索 到 九索
 *   27 到 33  字牌 東 南 西 北 白 發 中
 */

