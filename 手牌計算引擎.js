/**
 * 列舉手牌（不含副露）所有可能的「四面子一雀頭」拆解方式。
 * @param {number[]} 牌張數統計 長度 34 的陣列，記錄每種牌的張數
 * @returns {Array<{雀頭牌: number, 面子清單: Array<{種類: string, 起始牌: number}>}>}
 */
function 列舉標準型拆解(牌張數統計) {
  const 拆解結果清單 = [];
  for (let 雀頭候選牌 = 0; 雀頭候選牌 < 牌總數; 雀頭候選牌++) {
    if (牌張數統計[雀頭候選牌] < 2) continue;
    const 剩餘牌張數 = 牌張數統計.slice();
    剩餘牌張數[雀頭候選牌] -= 2;
    遞迴拆出面子(剩餘牌張數, 0, [], (面子清單) => {
      拆解結果清單.push({ 雀頭牌: 雀頭候選牌, 面子清單: 面子清單.map((面子) => ({ ...面子 })) });
    });
  }
  return 去除重複拆解(拆解結果清單);
}

function 遞迴拆出面子(剩餘牌張數, 搜尋起點, 已拆面子清單, 回報完成) {
  let 目前牌 = 搜尋起點;
  while (目前牌 < 牌總數 && 剩餘牌張數[目前牌] === 0) 目前牌++;
  if (目前牌 >= 牌總數) {
    回報完成(已拆面子清單);
    return;
  }

  if (剩餘牌張數[目前牌] >= 3) {
    剩餘牌張數[目前牌] -= 3;
    已拆面子清單.push({ 種類: '刻子', 起始牌: 目前牌 });
    遞迴拆出面子(剩餘牌張數, 目前牌, 已拆面子清單, 回報完成);
    已拆面子清單.pop();
    剩餘牌張數[目前牌] += 3;
  }

  const 可組順子 = !是字牌(目前牌) && 取得牌面數字(目前牌) <= 7
    && 剩餘牌張數[目前牌 + 1] > 0 && 剩餘牌張數[目前牌 + 2] > 0;
  if (可組順子) {
    剩餘牌張數[目前牌]--; 剩餘牌張數[目前牌 + 1]--; 剩餘牌張數[目前牌 + 2]--;
    已拆面子清單.push({ 種類: '順子', 起始牌: 目前牌 });
    遞迴拆出面子(剩餘牌張數, 目前牌, 已拆面子清單, 回報完成);
    已拆面子清單.pop();
    剩餘牌張數[目前牌]++; 剩餘牌張數[目前牌 + 1]++; 剩餘牌張數[目前牌 + 2]++;
  }
}

function 去除重複拆解(拆解結果清單) {
  const 已出現指紋 = new Set();
  const 去重後清單 = [];
  for (const 拆解 of 拆解結果清單) {
    const 指紋 = 拆解.雀頭牌 + '|' + 拆解.面子清單
      .map((面子) => 面子.種類 + 面子.起始牌)
      .sort()
      .join(',');
    if (已出現指紋.has(指紋)) continue;
    已出現指紋.add(指紋);
    去重後清單.push(拆解);
  }
  return 去重後清單;
}

/** 判斷是否為七對子型（七組不同的對子） */
function 是七對子型(牌張數統計) {
  let 對子數 = 0;
  for (let 牌 = 0; 牌 < 牌總數; 牌++) {
    if (牌張數統計[牌] === 0) continue;
    if (牌張數統計[牌] !== 2) return false;
    對子數++;
  }
  return 對子數 === 7;
}

/** 判斷是否為國士無雙型，回傳 {成立, 是十三面} */
function 檢查國士無雙型(牌張數統計) {
  let 總張數 = 0;
  let 對子牌 = -1;
  for (let 牌 = 0; 牌 < 牌總數; 牌++) {
    const 張數 = 牌張數統計[牌];
    if (張數 === 0) continue;
    if (!是么九或字牌(牌)) return { 成立: false, 對子牌: -1 };
    if (張數 > 2) return { 成立: false, 對子牌: -1 };
    if (張數 === 2) {
      if (對子牌 !== -1) return { 成立: false, 對子牌: -1 };
      對子牌 = 牌;
    }
    總張數 += 張數;
  }
  const 種類齊全 = 么九與字牌清單.every((牌) => 牌張數統計[牌] >= 1);
  if (總張數 !== 14 || 對子牌 === -1 || !種類齊全) return { 成立: false, 對子牌: -1 };
  return { 成立: true, 對子牌 };
}

