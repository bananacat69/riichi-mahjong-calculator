/**
 * 寶牌清單填的是寶牌本身，不是牌山翻開的指示牌，表寶牌與裏寶牌一起填在同一份清單。
 * 每一筆各算一次：同一種牌被兩張指示牌指到時放兩次，那種牌在手牌裡每張就算兩番。
 */
function 計算寶牌番數(和牌條件, 全部牌張統計) {
  let 寶牌數 = 0;
  for (const 寶牌 of 和牌條件.寶牌清單) {
    寶牌數 += 全部牌張統計[寶牌];
  }
  return { 寶牌數, 赤寶牌數: 和牌條件.赤寶牌張數 || 0 };
}

