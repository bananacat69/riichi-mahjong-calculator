/** 統計包含副露在內的全部牌張（槓子算四張） */
function 統計全部牌張(和牌條件) {
  const 牌張數統計 = 統計手牌張數(和牌條件.手牌);
  for (const 副露 of 和牌條件.副露清單) {
    if (副露.種類 === '吃') {
      牌張數統計[副露.起始牌]++;
      牌張數統計[副露.起始牌 + 1]++;
      牌張數統計[副露.起始牌 + 2]++;
    } else if (副露.種類 === '碰') {
      牌張數統計[副露.起始牌] += 3;
    } else {
      牌張數統計[副露.起始牌] += 4;
    }
  }
  return 牌張數統計;
}

/** 判斷某張牌對這位玩家來說是不是役牌（三元牌、場風、自風） */
function 是役牌(牌編號, 和牌條件) {
  if (三元牌清單.includes(牌編號)) return true;
  return 牌編號 === 和牌條件.場風牌 || 牌編號 === 和牌條件.自風牌;
}

/** 取得出現過的花色集合，用於混一色、清一色判定 */
function 取得出現花色集合(牌張數統計) {
  const 花色集合 = new Set();
  for (let 牌 = 0; 牌 < 牌總數; 牌++) {
    if (牌張數統計[牌] > 0) 花色集合.add(取得花色(牌));
  }
  return 花色集合;
}

/**
 * 判定一個和牌形成立的所有役。
 * @returns {{役滿清單: Array, 普通役清單: Array, 役滿總倍數: number}}
 */
function 判定所有役(和牌形, 和牌條件) {
  const 全部牌張統計 = 統計全部牌張(和牌條件);
  const 役滿清單 = 判定役滿(和牌形, 和牌條件, 全部牌張統計);
  if (役滿清單.length > 0) {
    const 役滿總倍數 = 役滿清單.reduce((累計, 役) => 累計 + 役.倍數, 0);
    return { 役滿清單, 普通役清單: [], 役滿總倍數 };
  }
  return { 役滿清單: [], 普通役清單: 判定普通役(和牌形, 和牌條件, 全部牌張統計), 役滿總倍數: 0 };
}

function 判定役滿(和牌形, 和牌條件, 全部牌張統計) {
  const 役滿清單 = [];
  const 面子清單 = 和牌形.面子清單;
  const 刻子與槓子清單 = 面子清單.filter((面子) => 面子.種類 === '刻子' || 面子.種類 === '槓子');

  // 天和、地和：發牌後第一巡自摸和牌，且完全沒有副露動作
  if (和牌條件.是天和 && 和牌形.是門前 && 和牌條件.是自摸) {
    役滿清單.push({ 名稱: '天和', 倍數: 1 });
  }
  if (和牌條件.是地和 && 和牌形.是門前 && 和牌條件.是自摸) {
    役滿清單.push({ 名稱: '地和', 倍數: 1 });
  }

  if (和牌形.形狀 === '國士無雙') {
    役滿清單.push({ 名稱: 和牌形.是十三面 ? '國士無雙十三面' : '國士無雙', 倍數: 1 });
    return 役滿清單;
  }

  if (和牌形.形狀 === '標準') {
    // 四暗刻：四組刻子或槓子全部是暗的
    const 暗刻與暗槓數 = 刻子與槓子清單.filter((面子) => 面子.是暗的).length;
    if (暗刻與暗槓數 === 4) {
      役滿清單.push({ 名稱: 和牌形.待牌形 === '單騎' ? '四暗刻單騎' : '四暗刻', 倍數: 1 });
    }

    // 大三元、小四喜、大四喜
    const 三元刻子數 = 刻子與槓子清單.filter((面子) => 三元牌清單.includes(面子.起始牌)).length;
    if (三元刻子數 === 3) 役滿清單.push({ 名稱: '大三元', 倍數: 1 });

    const 風牌刻子數 = 刻子與槓子清單.filter((面子) => 風牌清單.includes(面子.起始牌)).length;
    if (風牌刻子數 === 4) {
      役滿清單.push({ 名稱: '大四喜', 倍數: 1 });
    } else if (風牌刻子數 === 3 && 風牌清單.includes(和牌形.雀頭牌)) {
      役滿清單.push({ 名稱: '小四喜', 倍數: 1 });
    }

    // 四槓子
    if (面子清單.filter((面子) => 面子.種類 === '槓子').length === 4) {
      役滿清單.push({ 名稱: '四槓子', 倍數: 1 });
    }

    // 九蓮寶燈：門前清一色，形狀為 1112345678999 加任意一張同花色牌
    if (和牌條件.副露清單.length === 0 && 檢查九蓮寶燈(全部牌張統計)) {
      const 是純正九蓮 = 檢查純正九蓮寶燈(全部牌張統計, 和牌條件.和牌張);
      役滿清單.push({ 名稱: 是純正九蓮 ? '純正九蓮寶燈' : '九蓮寶燈', 倍數: 1 });
    }
  }

  // 字一色、綠一色、清老頭：七對子型的字一色同樣成立
  const 出現牌清單 = [];
  for (let 牌 = 0; 牌 < 牌總數; 牌++) if (全部牌張統計[牌] > 0) 出現牌清單.push(牌);

  if (出現牌清單.every((牌) => 是字牌(牌))) {
    役滿清單.push({ 名稱: '字一色', 倍數: 1 });
  }
  if (和牌形.形狀 === '標準') {
    if (出現牌清單.every((牌) => 綠一色允許牌清單.includes(牌))) {
      役滿清單.push({ 名稱: '綠一色', 倍數: 1 });
    }
    if (出現牌清單.every((牌) => !是字牌(牌) && 是么九或字牌(牌))) {
      役滿清單.push({ 名稱: '清老頭', 倍數: 1 });
    }
  }

  return 役滿清單;
}

function 檢查九蓮寶燈(全部牌張統計) {
  const 花色集合 = 取得出現花色集合(全部牌張統計);
  if (花色集合.size !== 1) return false;
  const 花色 = [...花色集合][0];
  if (花色 === 3) return false;
  const 起始 = 花色 * 9;
  if (全部牌張統計[起始] < 3 || 全部牌張統計[起始 + 8] < 3) return false;
  for (let 位移 = 1; 位移 <= 7; 位移++) {
    if (全部牌張統計[起始 + 位移] < 1) return false;
  }
  let 總張數 = 0;
  for (let 位移 = 0; 位移 < 9; 位移++) 總張數 += 全部牌張統計[起始 + 位移];
  return 總張數 === 14;
}

/** 純正九蓮寶燈：和牌前已是 1112345678999 的九面聽 */
function 檢查純正九蓮寶燈(全部牌張統計, 和牌張) {
  const 扣除和牌張後 = 全部牌張統計.slice();
  扣除和牌張後[和牌張]--;
  const 花色 = 取得花色(和牌張);
  if (花色 === 3) return false;
  const 起始 = 花色 * 9;
  if (扣除和牌張後[起始] !== 3 || 扣除和牌張後[起始 + 8] !== 3) return false;
  for (let 位移 = 1; 位移 <= 7; 位移++) {
    if (扣除和牌張後[起始 + 位移] !== 1) return false;
  }
  return true;
}

function 判定普通役(和牌形, 和牌條件, 全部牌張統計) {
  const 役清單 = [];
  const 是門前 = 和牌形.是門前;
  const 面子清單 = 和牌形.面子清單;
  const 順子清單 = 面子清單.filter((面子) => 面子.種類 === '順子');
  const 刻子與槓子清單 = 面子清單.filter((面子) => 面子.種類 === '刻子' || 面子.種類 === '槓子');

  /* 立直相關（門前限定，由使用者勾選的和牌狀況決定） */
  if (是門前 && 和牌條件.是雙立直) {
    役清單.push({ 名稱: '雙立直', 番數: 2 });
  } else if (是門前 && 和牌條件.是立直) {
    役清單.push({ 名稱: '立直', 番數: 1 });
  }
  if ((和牌條件.是立直 || 和牌條件.是雙立直) && 和牌條件.是一發 && 是門前) {
    役清單.push({ 名稱: '一發', 番數: 1 });
  }
  if (是門前 && 和牌條件.是自摸) {
    役清單.push({ 名稱: '門前清自摸和', 番數: 1 });
  }

  /* 和牌當下的特殊狀況 */
  if (和牌條件.是嶺上開花) 役清單.push({ 名稱: '嶺上開花', 番數: 1 });
  if (和牌條件.是搶槓) 役清單.push({ 名稱: '搶槓', 番數: 1 });
  if (和牌條件.是海底摸月) 役清單.push({ 名稱: '海底摸月', 番數: 1 });
  if (和牌條件.是河底撈魚) 役清單.push({ 名稱: '河底撈魚', 番數: 1 });

  /* 七對子 */
  if (和牌形.形狀 === '七對子') {
    役清單.push({ 名稱: '七對子', 番數: 2 });
  }

  /* 斷么九：全部牌都不是么九字牌 */
  let 含有么九或字牌 = false;
  for (let 牌 = 0; 牌 < 牌總數; 牌++) {
    if (全部牌張統計[牌] > 0 && 是么九或字牌(牌)) { 含有么九或字牌 = true; break; }
  }
  if (!含有么九或字牌) 役清單.push({ 名稱: '斷么九', 番數: 1 });

  if (和牌形.形狀 === '標準') {
    /* 平和：門前、四組順子、雀頭不是役牌、兩面聽 */
    const 成立平和 = 是門前
      && 順子清單.length === 4
      && !是役牌(和牌形.雀頭牌, 和牌條件)
      && 和牌形.待牌形 === '兩面';
    if (成立平和) 役清單.push({ 名稱: '平和', 番數: 1 });

    /* 役牌：每一組三元牌刻子、場風刻子、自風刻子各算一番 */
    for (const 面子 of 刻子與槓子清單) {
      if (面子.起始牌 === 白板編號) 役清單.push({ 名稱: '役牌 白', 番數: 1 });
      if (面子.起始牌 === 青發編號) 役清單.push({ 名稱: '役牌 發', 番數: 1 });
      if (面子.起始牌 === 紅中編號) 役清單.push({ 名稱: '役牌 中', 番數: 1 });
      if (面子.起始牌 === 和牌條件.場風牌) {
        役清單.push({ 名稱: '場風 ' + 牌名稱表[和牌條件.場風牌], 番數: 1 });
      }
      if (面子.起始牌 === 和牌條件.自風牌) {
        役清單.push({ 名稱: '自風 ' + 牌名稱表[和牌條件.自風牌], 番數: 1 });
      }
    }

    /* 一盃口與二盃口：相同順子成對的組數 */
    const 順子出現次數 = new Map();
    for (const 順子 of 順子清單) {
      順子出現次數.set(順子.起始牌, (順子出現次數.get(順子.起始牌) || 0) + 1);
    }
    let 相同順子成對組數 = 0;
    for (const 次數 of 順子出現次數.values()) 相同順子成對組數 += Math.floor(次數 / 2);
    if (是門前 && 相同順子成對組數 >= 2) {
      役清單.push({ 名稱: '二盃口', 番數: 3 });
    } else if (是門前 && 相同順子成對組數 === 1) {
      役清單.push({ 名稱: '一盃口', 番數: 1 });
    }

    /* 三色同順 */
    const 有三色同順 = [0, 1, 2, 3, 4, 5, 6].some((起始數字位移) =>
      [0, 1, 2].every((花色) => 順子清單.some((順子) => 順子.起始牌 === 花色 * 9 + 起始數字位移))
    );
    if (有三色同順) 役清單.push({ 名稱: '三色同順', 番數: 是門前 ? 2 : 1 });

    /* 一氣通貫 */
    const 有一氣通貫 = [0, 1, 2].some((花色) =>
      [0, 3, 6].every((起始數字位移) => 順子清單.some((順子) => 順子.起始牌 === 花色 * 9 + 起始數字位移))
    );
    if (有一氣通貫) 役清單.push({ 名稱: '一氣通貫', 番數: 是門前 ? 2 : 1 });

    /* 對對和、三暗刻、三槓子、三色同刻 */
    if (刻子與槓子清單.length === 4) 役清單.push({ 名稱: '對對和', 番數: 2 });

    const 暗刻與暗槓數 = 刻子與槓子清單.filter((面子) => 面子.是暗的).length;
    if (暗刻與暗槓數 === 3) 役清單.push({ 名稱: '三暗刻', 番數: 2 });

    const 槓子數 = 面子清單.filter((面子) => 面子.種類 === '槓子').length;
    if (槓子數 === 3) 役清單.push({ 名稱: '三槓子', 番數: 2 });

    const 有三色同刻 = [0, 1, 2, 3, 4, 5, 6, 7, 8].some((數字位移) =>
      [0, 1, 2].every((花色) => 刻子與槓子清單.some((面子) => 面子.起始牌 === 花色 * 9 + 數字位移))
    );
    if (有三色同刻) 役清單.push({ 名稱: '三色同刻', 番數: 2 });

    /* 小三元 */
    const 三元刻子數 = 刻子與槓子清單.filter((面子) => 三元牌清單.includes(面子.起始牌)).length;
    if (三元刻子數 === 2 && 三元牌清單.includes(和牌形.雀頭牌)) {
      役清單.push({ 名稱: '小三元', 番數: 2 });
    }

    /* 混全帶么九與純全帶么九 */
    const 每組都含么九 = 面子清單.every(面子是否含么九牌) && 是么九或字牌(和牌形.雀頭牌);
    if (每組都含么九) {
      let 含有字牌 = 是字牌(和牌形.雀頭牌) || 面子清單.some((面子) => 是字牌(面子.起始牌));
      if (含有字牌) {
        役清單.push({ 名稱: '混全帶么九', 番數: 是門前 ? 2 : 1 });
      } else {
        役清單.push({ 名稱: '純全帶么九', 番數: 是門前 ? 3 : 2 });
      }
    }
  }

  /* 混老頭：全部牌都是么九牌或字牌（七對子型同樣成立） */
  let 全部都是么九字牌 = true;
  for (let 牌 = 0; 牌 < 牌總數; 牌++) {
    if (全部牌張統計[牌] > 0 && !是么九或字牌(牌)) { 全部都是么九字牌 = false; break; }
  }
  if (全部都是么九字牌) 役清單.push({ 名稱: '混老頭', 番數: 2 });

  /* 混一色與清一色 */
  const 花色集合 = 取得出現花色集合(全部牌張統計);
  const 數牌花色清單 = [...花色集合].filter((花色) => 花色 !== 3);
  if (數牌花色清單.length === 1 && !花色集合.has(3)) {
    役清單.push({ 名稱: '清一色', 番數: 是門前 ? 6 : 5 });
  } else if (數牌花色清單.length === 1 && 花色集合.has(3)) {
    役清單.push({ 名稱: '混一色', 番數: 是門前 ? 3 : 2 });
  } else if (數牌花色清單.length === 0 && 花色集合.has(3)) {
    役清單.push({ 名稱: '混一色', 番數: 是門前 ? 3 : 2 });
  }

  return 役清單;
}

/** 面子是否包含么九牌或字牌 */
function 面子是否含么九牌(面子) {
  if (面子.種類 !== '順子') return 是么九或字牌(面子.起始牌);
  return 是么九或字牌(面子.起始牌) || 是么九或字牌(面子.起始牌 + 2);
}

